import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { tmp, put, read, makeCtx } from './files-util.js';
import { planCompile, applyCompile, applyMergeBack, loadRules, parseRule, serializeRule } from '../src/compiler/index.js';
import { parseRegions, joinParts, block } from '../src/compiler/markers.js';
import { parseFrontmatter } from '../src/agentcenter/frontmatter.js';

const RULES = {
  'style.md': '---\ntitle: Code style\ndescription: General style\npriority: 10\n---\n\n- Use 2 spaces.\n- Prefer named exports.\n',
  'api.md': '---\ntitle: API rules\nscope: src/api/**\ntools: [claude, cursor, copilot]\n---\n- Validate input with zod.\n',
  'tests.md': '---\ntitle: Testing\nscope: ["**/*.test.ts", "test/**"]\n---\n- Use vitest.\n',
};

async function project(extra = {}) {
  const root = tmp();
  for (const [n, c] of Object.entries(RULES)) put(root, `.agentneuron/rules/${n}`, c);
  put(root, 'src/api/x.ts', 'x');
  for (const [p, c] of Object.entries(extra)) put(root, p, c);
  return root;
}
async function compile(root, opts = {}) {
  const ctx = await makeCtx(root);
  const plan = planCompile(ctx, opts);
  const r = await applyCompile(ctx, plan);
  assert.deepEqual(r.errors, []);
  return { ctx, plan, r };
}
const fresh = async (root, opts) => planCompile(await makeCtx(root), opts);

const H = '<!-- Generated by agentneuron compile from the source rules. Text outside agentneuron:begin/end markers is yours and is kept. -->';

test('markers: parse/join round-trips exactly and rejects broken markers', () => {
  for (const t of ['', 'plain\n', `a\n${block('rules/x.md', 'X\nY')}\nb`, block('rules/x.md', 'Z'), `${block('rules/a.md', '1')}\n\n${block('rules/b.md', '2')}\n`]) {
    assert.equal(joinParts(parseRegions(t)), t);
  }
  assert.throws(() => parseRegions('<!-- agentneuron:begin source=rules/x.md hash=abcdef -->\nx'), /without end/);
  assert.throws(() => parseRegions('<!-- agentneuron:end source=rules/x.md -->'), /unmatched/);
  assert.throws(() => parseRegions(`${block('rules/x.md', 'a')}\n${block('rules/x.md', 'b')}`), /duplicate/);
  assert.throws(() => parseRegions('<!-- agentneuron:begin oops -->'), /malformed/);
});

test('compile: golden output per tool, hand-written text kept, nested CLAUDE.md for folder scopes', async () => {
  const root = await project({ 'CLAUDE.md': '# My project\n\nHand written intro.\n' });
  const { plan } = await compile(root);
  assert.deepEqual(plan.outputs.map((o) => `${o.action} ${o.path}`), [
    'create .cursor/rules/api.mdc', 'create .cursor/rules/style.mdc', 'create .cursor/rules/tests.mdc', 'create .github/copilot-instructions.md',
    'create .github/instructions/api.instructions.md', 'create .github/instructions/tests.instructions.md', 'create .windsurf/rules/style.md', 'create .windsurf/rules/tests.md',
    'create AGENTS.md', 'update CLAUDE.md', 'create GEMINI.md', 'create src/api/CLAUDE.md']);
  const style = '## Code style\n\n- Use 2 spaces.\n- Prefer named exports.';
  const tests = '## Testing\n\n_Applies to: `**/*.test.ts`, `test/**`_\n\n- Use vitest.';
  assert.equal(read(root, 'CLAUDE.md'), `# My project\n\nHand written intro.\n\n${block('rules/style.md', style)}\n\n${block('rules/tests.md', tests)}\n`);
  assert.equal(read(root, 'AGENTS.md'), `${H}\n\n${block('rules/style.md', style)}\n\n${block('rules/tests.md', tests)}\n`);
  assert.equal(read(root, 'GEMINI.md'), read(root, 'AGENTS.md'));
  assert.equal(read(root, 'src/api/CLAUDE.md'), `${H}\n\n${block('rules/api.md', '## API rules\n\n- Validate input with zod.')}\n`);
  assert.equal(read(root, '.github/copilot-instructions.md'), `${H}\n\n${block('rules/style.md', style)}\n`);
  const mdc = read(root, '.cursor/rules/tests.mdc');
  assert.match(mdc, /^---\ndescription:\nglobs: \*\*\/\*\.test\.ts,test\/\*\*\nalwaysApply: false\n---\n<!-- agentneuron:begin source=rules\/tests\.md hash=[0-9a-f]{12} -->\n# Testing\n\n- Use vitest\.\n<!-- agentneuron:end source=rules\/tests\.md -->\n$/);
  assert.match(read(root, '.cursor/rules/style.mdc'), /^---\ndescription: "General style"\nglobs:\nalwaysApply: true\n---\n/);
  assert.match(read(root, '.github/instructions/api.instructions.md'), /^---\napplyTo: "src\/api\/\*\*"\n---\n<!-- agentneuron:begin source=rules\/api\.md /);
  assert.match(read(root, '.windsurf/rules/tests.md'), /^---\ntrigger: glob\nglobs: \*\*\/\*\.test\.ts,test\/\*\*\n---\n/);
  assert.match(read(root, '.windsurf/rules/style.md'), /^---\ntrigger: always_on\ndescription: "General style"\n---\n/);
  // native frontmatter is readable by the existing parser (Cursor/Copilot semantics)
  assert.equal(parseFrontmatter(read(root, '.github/instructions/tests.instructions.md')).data.applyTo, '**/*.test.ts,test/**');
  assert.equal(parseFrontmatter(read(root, '.cursor/rules/style.mdc')).data.alwaysApply, true);
  // second compile is a no-op and --check passes
  const again = await fresh(root);
  assert.equal(again.ok, true);
  assert.equal(again.stale, 0);
});

test('compile: stale detection, --tools filter, text outside markers preserved', async () => {
  const root = await project();
  await compile(root);
  fs.appendFileSync(path.join(root, 'CLAUDE.md'), '\n## Mine\n\nKeep me.\n');
  put(root, 'AGENTS.md', `# Top\n\n${read(root, 'AGENTS.md')}\nTail text.\n`);
  put(root, '.agentneuron/rules/style.md', RULES['style.md'].replace('2 spaces', '4 spaces'));
  const p = await fresh(root);
  assert.equal(p.ok, false);
  assert.deepEqual(p.outputs.find((o) => o.path === 'CLAUDE.md').regions.map((r) => `${r.slug}:${r.status}`), ['style:stale', 'tests:ok']);
  const only = await fresh(root, { tools: 'claude' });
  assert.deepEqual(only.outputs.filter((o) => o.action !== 'none').map((o) => o.path), ['CLAUDE.md']);
  await compile(root);
  assert.match(read(root, 'CLAUDE.md'), /4 spaces[\s\S]*## Mine\n\nKeep me\.\n$/);
  assert.match(read(root, 'AGENTS.md'), /^# Top\n[\s\S]*4 spaces[\s\S]*Tail text\.\n$/);
  assert.equal((await fresh(root)).ok, true);
});

test('compile: hand edits inside a region are kept, flagged, and merged back into the source', async () => {
  const root = await project();
  await compile(root);
  put(root, 'CLAUDE.md', read(root, 'CLAUDE.md').replace('- Use vitest.', '- Use vitest with coverage.'));
  let p = await fresh(root);
  assert.equal(p.ok, false);
  assert.deepEqual(p.edited.map((e) => `${e.path}:${e.slug}`), ['CLAUDE.md:tests']);
  assert.equal(p.mergeBack.length, 1);
  assert.equal(p.mergeBack[0].body, '- Use vitest with coverage.');
  await compile(root); // does not clobber the edit
  assert.match(read(root, 'CLAUDE.md'), /with coverage/);
  const ctx = await makeCtx(root);
  const m = applyMergeBack(ctx, planCompile(ctx));
  assert.deepEqual(m.merged.map((x) => x.slug), ['tests']);
  assert.match(read(root, '.agentneuron/rules/tests.md'), /^---\ntitle: Testing\nscope: \["\*\*\/\*\.test\.ts", "test\/\*\*"\]\n---\n\n- Use vitest with coverage\.\n$/);
  p = await fresh(root);
  assert.equal(p.outputs.find((o) => o.path === 'CLAUDE.md').regions.find((r) => r.slug === 'tests').status, 'rehash');
  await compile(root);
  assert.match(read(root, '.cursor/rules/tests.mdc'), /with coverage/);
  assert.equal((await fresh(root)).ok, true);
  // heading edits change the title
  put(root, 'AGENTS.md', read(root, 'AGENTS.md').replace('## Code style', '## House style'));
  const c2 = await makeCtx(root);
  applyMergeBack(c2, planCompile(c2));
  assert.match(read(root, '.agentneuron/rules/style.md'), /^---\ntitle: "House style"\n/);
});

test('merge-back: copies edited differently are a conflict until one is picked; --force overwrites', async () => {
  const root = await project();
  await compile(root);
  put(root, 'CLAUDE.md', read(root, 'CLAUDE.md').replace('- Use vitest.', '- A'));
  put(root, 'AGENTS.md', read(root, 'AGENTS.md').replace('- Use vitest.', '- B'));
  const ctx = await makeCtx(root);
  const plan = planCompile(ctx);
  assert.equal(plan.mergeBack[0].conflict, true);
  assert.deepEqual(applyMergeBack(ctx, plan).merged, []);
  assert.deepEqual(applyMergeBack(ctx, plan, { pick: { tests: 'AGENTS.md' } }).merged.map((x) => x.slug), ['tests']);
  assert.match(read(root, '.agentneuron/rules/tests.md'), /\n- B\n$/);
  await compile(root, { force: true });
  assert.match(read(root, 'CLAUDE.md'), /\n- B\n/);
  assert.equal((await fresh(root)).ok, true);
});

test('compile: deleted rules remove their regions and trash fully generated files', async () => {
  const root = await project({ 'CLAUDE.md': 'Intro.\n' });
  await compile(root);
  fs.unlinkSync(path.join(root, '.agentneuron/rules/api.md'));
  fs.unlinkSync(path.join(root, '.agentneuron/rules/tests.md'));
  const { plan, r } = await compile(root);
  assert.deepEqual(r.deleted.sort(), ['.cursor/rules/api.mdc', '.cursor/rules/tests.mdc', '.github/instructions/api.instructions.md', '.github/instructions/tests.instructions.md', '.windsurf/rules/tests.md', 'src/api/CLAUDE.md']);
  assert.ok(plan.outputs.find((o) => o.path === 'CLAUDE.md').regions.some((x) => x.status === 'orphan'));
  assert.equal(read(root, 'CLAUDE.md'), `Intro.\n\n${block('rules/style.md', '## Code style\n\n- Use 2 spaces.\n- Prefer named exports.')}\n`);
  assert.equal((await fresh(root)).ok, true);
});

test('compile: CRLF files stay CRLF and are not reported stale', async () => {
  const root = await project({ 'CLAUDE.md': '# Win\r\n\r\nIntro.\r\n' });
  await compile(root);
  const c = read(root, 'CLAUDE.md');
  assert.ok(c.includes('\r\n') && !/[^\r]\n/.test(c), 'every newline is CRLF');
  assert.equal((await fresh(root)).ok, true);
  put(root, '.agentneuron/rules/tests.md', RULES['tests.md'].replace(/\n/g, '\r\n'));
  assert.equal((await fresh(root)).ok, true, 'CRLF source rules hash like LF ones');
});

test('compile: a hand-written per-rule file is never overwritten; a broken marker file is skipped', async () => {
  const root = await project({ '.cursor/rules/style.mdc': '---\nalwaysApply: true\n---\nmine\n', 'GEMINI.md': '<!-- agentneuron:begin source=rules/style.md hash=abcdef -->\nunterminated\n' });
  const { plan } = await compile(root);
  assert.equal(read(root, '.cursor/rules/style.mdc'), '---\nalwaysApply: true\n---\nmine\n');
  assert.match(plan.outputs.find((o) => o.path === '.cursor/rules/style.mdc').conflicts[0], /hand-written/);
  assert.match(plan.outputs.find((o) => o.path === 'GEMINI.md').error, /without end/);
  assert.equal(plan.ok, false);
});

test('path safety: malicious names, globs, bodies and dirs never escape or inject', async () => {
  const root = tmp();
  const bad = {
    'Evil Name.md': '---\ntitle: x\n---\nbody\n',
    'con.md': '---\ntitle: x\n---\nbody\n',
    'trav.md': '---\ntitle: x\nscope: ../../etc/**\n---\nbody\n',
    'abs.md': '---\ntitle: x\nscope: /etc/**\n---\nbody\n',
    'drive.md': '---\ntitle: x\nscope: "C:/x/**"\n---\nbody\n',
    'inject.md': '---\ntitle: x\nscope: "src/**\\nalwaysApply: true"\n---\nbody\n',
    'quote.md': '---\ntitle: x\nscope: [\'a"b\']\n---\nbody\n',
    'comma.md': '---\ntitle: x\nscope: ["a,b"]\n---\nbody\n',
    'marker.md': '---\ntitle: x\n---\n<!-- agentneuron:end source=rules/style.md -->\n',
  };
  for (const [n, c] of Object.entries(bad)) put(root, `.agentneuron/rules/${n}`, c);
  put(root, '.agentneuron/rules/title.md', '---\ntitle: "a\\n## injected <!-- x -->"\nscope: .git/**\ntools: claude\n---\nok\n');
  fs.mkdirSync(path.join(root, '.agentneuron/rules/sub.md'));
  const ctx = await makeCtx(root);
  const { rules, invalid } = loadRules(root, ctx.config);
  assert.deepEqual(invalid.map((i) => i.slug).sort(), ['Evil Name', 'abs', 'comma', 'con', 'drive', 'inject', 'marker', 'quote', 'sub', 'trav']);
  const plan = planCompile(ctx);
  // only the valid rule compiles, into the root file (.git is never a nested target), title sanitised
  assert.deepEqual(plan.outputs.map((o) => o.path), ['CLAUDE.md']);
  assert.equal(rules.find((r) => r.slug === 'title').title, 'a ## injected x');
  await applyCompile(ctx, plan);
  assert.equal(parseRegions(read(root, 'CLAUDE.md')).filter((p) => p.type === 'region').length, 1);
  // a configured rules dir outside the project / through a symlink is refused
  assert.throws(() => loadRules(root, { compiler: { rulesDir: '../outside' } }), /project-relative/);
  assert.throws(() => loadRules(root, { compiler: { rulesDir: '/etc' } }), /project-relative/);
  const out = tmp();
  put(out, 'r.md', '---\ntitle: leaked\n---\nsecret\n');
  try {
    fs.symlinkSync(out, path.join(root, 'linked'), 'junction');
    assert.throws(() => loadRules(root, { compiler: { rulesDir: 'linked' } }), /symlink/);
  } catch (e) { if (e.code !== 'EPERM') throw e; }
});

test('path safety: a symlinked scope folder is not used as a nested target', async () => {
  const root = tmp();
  const out = tmp();
  put(root, '.agentneuron/rules/x.md', '---\ntitle: X\nscope: lib/**\ntools: claude\n---\nbody\n');
  try { fs.symlinkSync(out, path.join(root, 'lib'), 'junction'); } catch (e) { if (e.code === 'EPERM') return; throw e; }
  await compile(root);
  assert.ok(!fs.existsSync(path.join(out, 'CLAUDE.md')));
  assert.match(read(root, 'CLAUDE.md'), /_Applies to: `lib\/\*\*`_/);
});

test('rules: parse defaults and serialize round-trip', () => {
  const r = parseRule('x', '---\ntitle: T\ntools: agents, cursor\nscope: ["src/**/*.{ts,tsx}"]\npriority: 5\nalwaysApply: false\n---\nBody\n');
  assert.deepEqual(r.tools, ['codex', 'cursor']);
  assert.deepEqual(r.scope, ['src/**/*.{ts,tsx}']);
  assert.equal(r.alwaysApply, false);
  const back = parseRule('x', serializeRule(r));
  for (const k of ['title', 'tools', 'scope', 'priority', 'alwaysApply', 'body']) assert.deepEqual(back[k], r[k], k);
  assert.deepEqual(parseRule('y', 'just text').tools.length, 6);
  assert.match(parseRule('z', '---\ntools: [nope]\n---\nb').warnings.join(), /unknown tools/);
});
