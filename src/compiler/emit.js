// Where and how each rule lands in each tool's native format.
import fs from 'node:fs';
import path from 'node:path';
import { resolveSafe } from '../files/paths.js';
import { isIgnored } from '../core/classify.js';
import { cleanText } from './safety.js';

export const ROOT_FILE = { claude: 'CLAUDE.md', codex: 'AGENTS.md', gemini: 'GEMINI.md' };
// Every path the compiler may write, per tool. Anything else is refused.
export const ALLOWED = {
  claude: /^(?:[^/]+\/)*CLAUDE\.md$/,
  codex: /^(?:[^/]+\/)*AGENTS\.md$/,
  gemini: /^(?:[^/]+\/)*GEMINI\.md$/,
  cursor: /^\.cursor\/rules\/[a-z0-9-]+\.mdc$/,
  copilot: /^\.github\/(?:copilot-instructions\.md|instructions\/[a-z0-9-]+\.instructions\.md)$/,
  windsurf: /^(?:\.windsurfrules|\.windsurf\/rules\/[a-z0-9-]+\.md)$/,
};
export const toolOfPath = (p) => Object.keys(ALLOWED).find((t) => ALLOWED[t].test(p)) || null;
export const sourceOf = (slug) => `rules/${slug}.md`;
export const HEADER = '<!-- Generated by agentneuron compile from the source rules. Text outside agentneuron:begin/end markers is yours and is kept. -->';

const NESTED = /^([A-Za-z0-9_@+-][A-Za-z0-9_.@+-]*(?:\/[A-Za-z0-9_@+-][A-Za-z0-9_.@+-]*)*)\/\*\*(?:\/\*)?$/;
const q = (s) => JSON.stringify(String(s));

/** The folder a scoped rule can live in as a nested CLAUDE.md / AGENTS.md / GEMINI.md, or null. */
export function nestedDir(rule, root, config) {
  if (rule.scope.length !== 1) return null;
  const m = NESTED.exec(rule.scope[0]);
  if (!m || isIgnored(m[1], config) || m[1].split('/').some((s) => s.startsWith('.'))) return null;
  try {
    const { abs } = resolveSafe(root, m[1]); // refuses symlinked components and forbidden folders
    return fs.lstatSync(abs).isDirectory() ? m[1] : null;
  } catch { return null; }
}

export function windsurfMode(root, config) {
  const m = config?.compiler?.windsurf;
  if (m === 'rules' || m === 'legacy') return m;
  const has = (p) => { try { return fs.lstatSync(path.join(root, p)); } catch { return null; } };
  return has('.windsurfrules')?.isFile() && !has('.windsurf/rules')?.isDirectory() ? 'legacy' : 'rules';
}

/** Section inside a shared file (CLAUDE.md, AGENTS.md, ...). */
export function renderSection(rule, appliesTo) {
  const L = [`## ${rule.title}`, ''];
  if (appliesTo && rule.scope.length) L.push(`_Applies to: ${rule.scope.map((g) => `\`${g}\``).join(', ')}_`, '');
  L.push(rule.body);
  return L.join('\n').replace(/\s+$/, '');
}

/** Body of a per-rule file (.mdc, .instructions.md, .windsurf/rules/*.md). */
export const renderFileBody = (rule) => `# ${rule.title}\n\n${rule.body}`.replace(/\s+$/, '');

/** Native frontmatter for per-rule files. */
export function renderFrontmatter(rule, tool) {
  const scoped = rule.scope.length > 0;
  const desc = rule.description || '';
  const L = ['---'];
  if (tool === 'cursor') {
    L.push(`description: ${desc ? q(desc) : ''}`.trimEnd(), `globs: ${rule.scope.join(',')}`.trimEnd(), `alwaysApply: ${rule.alwaysApply ?? !scoped}`);
  } else if (tool === 'copilot') {
    L.push(`applyTo: ${q(rule.scope.join(','))}`);
    if (desc) L.push(`description: ${q(desc)}`);
  } else if (tool === 'windsurf') {
    const trigger = scoped ? 'glob' : rule.alwaysApply === false ? (desc ? 'model_decision' : 'manual') : 'always_on';
    L.push(`trigger: ${trigger}`);
    if (desc) L.push(`description: ${q(desc)}`);
    if (scoped) L.push(`globs: ${rule.scope.join(',')}`);
  }
  L.push('---');
  return L.join('\n');
}

/**
 * Placements of one rule for one tool: [{ path, kind: 'section'|'file', content, fm? }].
 * env: { root, config, windsurf }
 */
export function placements(rule, tool, env) {
  const scoped = rule.scope.length > 0;
  if (ROOT_FILE[tool]) {
    const dir = scoped ? nestedDir(rule, env.root, env.config) : null;
    return [{ path: dir ? `${dir}/${ROOT_FILE[tool]}` : ROOT_FILE[tool], kind: 'section', content: renderSection(rule, !dir) }];
  }
  if (tool === 'cursor') return [{ path: `.cursor/rules/${rule.slug}.mdc`, kind: 'file', fm: renderFrontmatter(rule, 'cursor'), content: renderFileBody(rule) }];
  if (tool === 'copilot') {
    if (!scoped) return [{ path: '.github/copilot-instructions.md', kind: 'section', content: renderSection(rule, false) }];
    return [{ path: `.github/instructions/${rule.slug}.instructions.md`, kind: 'file', fm: renderFrontmatter(rule, 'copilot'), content: renderFileBody(rule) }];
  }
  if (tool === 'windsurf') {
    if (env.windsurf === 'legacy') return [{ path: '.windsurfrules', kind: 'section', content: renderSection(rule, true) }];
    return [{ path: `.windsurf/rules/${rule.slug}.md`, kind: 'file', fm: renderFrontmatter(rule, 'windsurf'), content: renderFileBody(rule) }];
  }
  return [];
}

/** Inverse of renderSection / renderFileBody: recover { title, body } from (possibly hand-edited) region text. */
export function unrender(content, kind) {
  const lines = content.split('\n');
  let i = 0, title = null;
  const h = (kind === 'file' ? /^#\s+(.+?)\s*$/ : /^##\s+(.+?)\s*$/).exec(lines[0] || '');
  if (h) { title = cleanText(h[1], 120); i = 1; }
  while (i < lines.length && !lines[i].trim()) i++;
  if (kind === 'section' && /^_Applies to: .*_\s*$/.test(lines[i] || '')) { i++; while (i < lines.length && !lines[i].trim()) i++; }
  return { title, body: lines.slice(i).join('\n').replace(/\s+$/, '') };
}
