// Markdown renderers for briefs, context packs and debug reports (pasted into another agent).
// Inputs are already masked; inline code is fenced safely.
import { fmtTs } from './util.js';

const code = (s) => { const t = String(s ?? ''); const n = Math.max(1, ...[...t.matchAll(/`+/g)].map((m) => m[0].length + 1)); const f = '`'.repeat(n); return `${f}${t.includes('`') ? ` ${t} ` : t}${f}`; };
const one = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const evText = (list = []) => (list.length ? ` _(${list.slice(0, 3).map((e) => `${e.kind}${e.ref ? ` ${e.kind === 'commit' ? String(e.ref).slice(0, 7) : e.ref}` : ''}`).join(', ')})_` : '');

function itemLine(i) {
  let t = one(i.label || '');
  if (i.title) t += `${t ? ': ' : ''}${one(i.title)}`;
  if (i.command) t += ` ${code(one(i.command))}`;
  if (i.quote) t += ` — "${one(i.quote)}"`;
  if (i.path && !t.includes(i.path)) t += ` (${code(i.path)})`;
  return `- ${t}${evText(i.evidence)}`;
}

function section(L, title, items, empty) {
  L.push(`## ${title}`, '');
  if (!items.length) L.push(`_${empty}_`);
  else for (const i of items) L.push(itemLine(i));
  L.push('');
}

export function resumeMarkdown(b) {
  const L = [];
  L.push(`# Resume brief: ${one(b.title) || (b.task ? b.task.id : b.source.session) || 'latest work'}`, '');
  const src = [b.task && `task \`${b.task.id}\`${b.task.status ? ` (${b.task.status})` : ''}`, b.source.sessions?.length && `session${b.source.sessions.length > 1 ? 's' : ''} ${b.source.sessions.map((s) => `\`${s}\``).join(', ')}`].filter(Boolean).join(' · ');
  L.push(`> Generated by AgentNeuron ${fmtTs(b.generatedAt)} from ${src || 'project data'}. Every item lists its evidence. Continue the work from here; verify before assuming anything is done.`, '');
  L.push('## Goal', '');
  if (b.task?.title) L.push(`Task: ${one(b.task.title)}`, '');
  L.push(b.goal?.prompt ? `> ${one(b.goal.prompt)}` : '_No prompt recorded._', '');
  if (b.lastPrompt) L.push(`Last request: > ${one(b.lastPrompt)}`, '');
  section(L, 'Done', b.done, 'Nothing recorded as done.');
  section(L, 'Failed attempts (do not repeat blindly)', b.failed, 'No failures recorded.');
  section(L, 'Decisions and corrections', b.decisions, 'No user corrections recorded.');
  L.push('## Files', '');
  if (!b.files.length) L.push('_No files changed._');
  for (const f of b.files.slice(0, 40)) L.push(`- ${code(f.path)}${f.edits ? ` — ${f.edits} edit${f.edits === 1 ? '' : 's'}` : ''}`);
  L.push('');
  L.push('## Tests and checks', '');
  if (!b.runs.length) L.push('_No verification runs recorded (run the tests before continuing)._');
  for (const r of b.runs) {
    L.push(`- ${r.kind}: ${r.failed ? `**${r.failed} failing**` : r.exitCode === 0 ? 'passing' : `exit ${r.exitCode ?? '?'}`}${r.passed != null ? `, ${r.passed} passed` : ''}${r.command ? ` (${code(r.command)})` : ''} ${fmtTs(r.endedAt || r.startedAt)}`);
    for (const f of r.failures.slice(0, 5)) L.push(`  - ${one(f.name)}${f.file ? ` in ${code(f.file)}` : ''}${f.quote ? `: ${one(f.quote)}` : ''}`);
  }
  L.push('');
  if (b.todos.length) {
    L.push('## Open todos', '');
    for (const t of b.todos) L.push(`- [${t.status === 'completed' ? 'x' : ' '}] ${one(t.title || t.label)}${t.status === 'in_progress' ? ' _(in progress)_' : ''}`);
    L.push('');
  }
  if (b.criteria.length) {
    L.push('## Acceptance criteria', '');
    for (const c of b.criteria) L.push(`- [${c.status === 'verified' ? 'x' : ' '}] ${one(c.label)} — ${c.status}`);
    L.push('');
  }
  section(L, 'Next steps', b.next, 'No open next steps were derived; check the goal against the done list.');
  return L.join('\n');
}

export function packMarkdown(p) {
  const L = [];
  L.push(`# Context pack: ${one(p.task.text) || p.task.id || 'task'}`, '');
  L.push(`> ${p.items.length} items, ~${p.tokens} of ${p.budget} tokens. Ranked by relevance to the task (deterministic, no model). Read the files in this order.`, '');
  const by = (k) => p.items.filter((i) => i.kind === k);
  const files = by('file');
  if (files.length) {
    L.push('## Files', '');
    for (const i of files) L.push(`- ${code(i.path)} (~${i.tokens} tokens) — ${one(i.reason)}`);
    L.push('');
  }
  const tests = by('test');
  if (tests.length) {
    L.push('## Related tests', '');
    for (const i of tests) L.push(`- ${code(i.path)} — ${one(i.reason)}`);
    L.push('');
  }
  const rules = by('rule');
  if (rules.length) {
    L.push('## Rules and context', '');
    for (const i of rules) { L.push(`### ${code(i.path)}${i.heading ? ` — ${one(i.heading)}` : ''}`, '', String(i.text || '').trim(), ''); }
  }
  const facts = by('fact');
  if (facts.length) {
    L.push('## Verified facts', '');
    for (const i of facts) L.push(`- ${one(i.text)}${i.path ? ` (${code(i.path)})` : ''}`);
    L.push('');
  }
  if (p.skipped?.length) L.push(`_${p.skipped.length} more candidate(s) did not fit the budget._`, '');
  return L.join('\n');
}

export function debugMarkdown(r) {
  const L = [];
  L.push(`# Bug report: ${one(r.error.type || 'Error')}${r.error.quote ? `: ${one(r.error.quote)}` : ''}`, '');
  L.push(`> Generated by AgentNeuron ${fmtTs(r.generatedAt)} from ${r.source === 'run' ? 'the last failing run' : 'a pasted error'}. Hypotheses are ranked by evidence, not certainty: confirm each before changing code.`, '');
  L.push('## Stack frames in this project', '');
  const own = r.frames.filter((f) => f.inProject);
  if (!own.length) L.push('_No frames map to project files._');
  for (const f of own.slice(0, 15)) L.push(`- ${code(`${f.path}:${f.line || '?'}`)}${f.fn ? ` in ${code(f.fn)}` : ''}${f.recent ? ' — changed recently' : ''}`);
  L.push('');
  L.push('## Hypotheses', '');
  if (!r.hypotheses.length) L.push('_No hypothesis has supporting evidence. Reproduce the error with more output._', '');
  r.hypotheses.forEach((h, i) => {
    L.push(`### ${i + 1}. ${one(h.title)} (${Math.round(h.confidence * 100)}%)`, '');
    for (const e of h.evidence) L.push(`- ${one(e.label)}${e.ref ? ` (${code(e.ref)})` : ''}`);
    L.push('', `**How to confirm:** ${one(h.check)}`, '');
  });
  const rel = r.related;
  if (rel.commits.length) { L.push('## Recent commits on these files', ''); for (const c of rel.commits) L.push(`- ${code(c.short || c.hash.slice(0, 7))} ${one(c.subject)} ${fmtTs(c.ts)}`); L.push(''); }
  if (rel.config.length) { L.push('## Config and env', ''); for (const c of rel.config) L.push(`- ${one(c.label)}`); L.push(''); }
  if (rel.deps.length) { L.push('## Dependencies involved', ''); for (const d of rel.deps) L.push(`- ${code(d.name)} declared ${d.declared || '—'}, installed ${d.installed || '—'}`); L.push(''); }
  if (rel.tests.length) { L.push('## Failing tests', ''); for (const t of rel.tests) L.push(`- ${one(t.name)}${t.file ? ` (${code(t.file)})` : ''}`); L.push(''); }
  if (rel.sessions.length) { L.push('## Similar past failures', ''); for (const s of rel.sessions) L.push(`- ${s.command ? code(s.command) : ''}${s.quote ? ` — "${one(s.quote)}"` : ''}${s.fix ? ` → fixed by ${code(s.fix)}` : ''}`); L.push(''); }
  return L.join('\n');
}
